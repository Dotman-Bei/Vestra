// Regenerates lib/chain/abi.ts from the Foundry build output. Run after changing the contract:
//   (cd ../contracts && forge build) && npm run abi
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const artifact = JSON.parse(
  readFileSync(new URL("../../contracts/out/VestraRegistry.sol/VestraRegistry.json", import.meta.url), "utf8"),
);
const out = `// Generated by scripts/gen-abi.mjs from contracts/out. Do not edit by hand.\nexport const registryAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`;
writeFileSync(`${root}lib/chain/abi.ts`, out);
console.log(`Wrote lib/chain/abi.ts (${artifact.abi.length} entries)`);
